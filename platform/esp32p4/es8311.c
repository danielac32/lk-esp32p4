#define COEFF_COUNT (sizeof(s_coeff_div) / sizeof(s_coeff_div[0]))

static bool codec, mic;
static uint8_t mic_pga = P4_ES8311_MIC_PGA_MAX;
static uint8_t mic_vol = ES_MIC_VOLUME;
static uint8_t mic_scale = ES_MIC_SCALE;
static bool i2c_ready;

static void es_i2c_init(void) {
    if (!i2c_ready) { p4_i2c_init(); i2c_ready = true; }
}
static bool reg_write(uint8_t reg, uint8_t value) {
    return p4_i2c_write_reg8(P4_ES8311_ADDR0, reg, value);
}
static bool reg_read(uint8_t reg, uint8_t *value) {
    return p4_i2c_read_regs(P4_ES8311_ADDR0, reg, value, 1);
}
static bool reg_update(uint8_t reg, uint8_t mask, uint8_t value) {
    uint8_t cur;
    if (!reg_read(reg, &cur)) return false;
    cur = (uint8_t)((cur & ~mask) | (value & mask));
    return reg_write(reg, cur);
}
static const struct coeff *coeff_find(uint32_t mclk, uint32_t rate) {
    for (unsigned i = 0; i < COEFF_COUNT; i++)
        if (s_coeff_div[i].mclk_hz == mclk && s_coeff_div[i].sample_rate_hz == rate)
            return &s_coeff_div[i];
    return NULL;
}

static bool es8311_apply_config(void) {
    const struct coeff *c = coeff_find(P4_ES8311_MCLK_HZ, P4_ES8311_SAMPLE_RATE_HZ);
    uint8_t reg06;
    if (!c) return false;
    if (!reg_write(ES_REG_CLK01, 0x3FU)) return false;
    if (!reg_update(ES_REG_CLK02, 0xF8U,
                    (uint8_t)(((c->pre_div - 1U) << 5) | (c->pre_multi << 3))) ||
        !reg_write(ES_REG_CLK03, (uint8_t)((c->fs_mode << 6) | c->adc_osr)) ||
        !reg_write(ES_REG_CLK04, c->dac_osr) ||
        !reg_write(ES_REG_CLK05, (uint8_t)(((c->adc_div - 1U) << 4) | c->dac_div)))
        return false;
    if (!reg_read(ES_REG_CLK06, &reg06)) return false;
    reg06 = (uint8_t)(reg06 & ~(ES_BIT(5) | 0x1FU));
    reg06 |= (c->bclk_div < 19U) ? (uint8_t)(c->bclk_div - 1U) : c->bclk_div;
    if (!reg_write(ES_REG_CLK06, reg06) ||
        !reg_update(ES_REG_CLK07, 0x3FU, c->lrck_h) ||
        !reg_write(ES_REG_CLK08, c->lrck_l)) return false;
    if (!reg_update(ES_REG_RESET, 0x40U, 0x00U) ||
        !reg_write(ES_REG_SDPIN, ES_FORMAT_16BIT) ||
        !reg_write(ES_REG_SDPOUT, ES_FORMAT_16BIT)) return false;
    if (!reg_write(ES_REG_SYS0D, 0x01U) || !reg_write(ES_REG_SYS0E, 0x02U) ||
        !reg_write(ES_REG_SYS12, 0x00U) || !reg_write(ES_REG_SYS13, 0x10U) ||
        !reg_write(ES_REG_ADC1C, 0x6AU) || !reg_write(ES_REG_DAC37, 0x08U)) return false;
    return true;
}

uint8_t p4_es8311_reg_read(uint8_t reg) { uint8_t v = 0; if (!reg_read(reg, &v)) return 0xFF; return v; }
void p4_es8311_reg_write(uint8_t reg, uint8_t val) { reg_write(reg, val); }

bool p4_es8311_init(void) {
    es_i2c_init();
    codec = false;
    uint8_t id = 0;
    /* Leer registro 0x00 de vuelta confirma que el codec responde (evitamos
     * p4_i2c_probe: deja el FSM en mal estado, medido en placa). */
    if (!reg_read(ES_REG_RESET, &id)) return false;
    if (!coeff_find(P4_ES8311_MCLK_HZ, P4_ES8311_SAMPLE_RATE_HZ)) return false;
    if (!reg_write(ES_REG_RESET, 0x1FU)) return false;
    spin(20000U);  /* 20 ms */
    if (!reg_write(ES_REG_RESET, 0x00U) || !reg_write(ES_REG_RESET, 0x80U)) return false;
    if (!es8311_apply_config()) return false;
    codec = true;
    return true;
}

bool p4_es8311_present(void) { return codec; }

int p4_es8311_set_volume(uint32_t percent) {
    uint8_t reg32 = 0;
    if (!codec) return -1;
    if (percent > 100U) percent = 100U;
    if (percent > 0U) reg32 = (uint8_t)(((percent * 256U) / 100U) - 1U);
    if (!reg_write(ES_REG_DAC32, reg32)) return -1;
    return p4_es8311_get_volume();
}
int p4_es8311_get_volume(void) {
    uint8_t r;
    if (!codec || !reg_read(ES_REG_DAC32, &r)) return -1;
    if (r == 0U) return 0;
    return (int)((r * 100U) / 256U) + 1;
}
int p4_es8311_get_volume_db(void) {
    uint8_t r;
    if (!codec || !reg_read(ES_REG_DAC32, &r)) return -1;
    if (r == 0U) return P4_ES8311_VOL_MUTE_DB10;
    return ((int)r - P4_ES8311_VOL_0DB_REG) * P4_ES8311_VOL_STEP_DB10;
}
bool p4_es8311_set_mute(bool mute) {
    uint8_t v = mute ? (uint8_t)(ES_BIT(6) | ES_BIT(5)) : 0U;
    return codec && reg_update(ES_REG_DAC31, ES_BIT(6) | ES_BIT(5), v);
}
int p4_es8311_get_mute(void) {
    uint8_t r;
    if (!codec || !reg_read(ES_REG_DAC31, &r)) return -1;
    return (r & (ES_BIT(6) | ES_BIT(5))) != 0;
}










bool p4_es8311_start_mic(void)
{
    if (!codec)
    {
        return false;
    }

    if (!reg_update(ES_REG_SYS0E, ES_BIT(6), 0U) ||
        !reg_write(ES_REG_SYS14, (uint8_t)(ES_BIT(4) | mic_pga)) ||
        !reg_write(ES_REG_ADC16, mic_scale) ||
        !reg_write(ES_REG_ADC17, mic_vol))
    {
        return false;
    }

    mic = true;
    return true;
}
bool p4_es8311_stop_mic(void)
{
    if (!codec)
    {
        return false;
    }

    if (!reg_write(ES_REG_ADC17, 0U) ||
        !reg_write(ES_REG_SYS14, 0U) ||
        !reg_update(ES_REG_SYS0E, ES_BIT(6), ES_BIT(6)))
    {
        return false;
    }

    mic = false;
    return true;
}
